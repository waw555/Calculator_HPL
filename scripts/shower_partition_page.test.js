assert.doesNotMatch(page.match(/<input id="object_name"[^>]*>/)?.[0] || '', /\brequired\b/, 'Поле объекта не должно блокировать расчёт');
assert.match(page, /id="panel_format_id"/, 'Должен быть выбор формата листа');
